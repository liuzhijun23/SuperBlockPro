static int16_t predictor;
static int8_t step_index;
static uint16_t adpcm_byte_pos;
static uint8_t use_high_nibble;
static const uint8_t * volatile clip_data;
static uint16_t clip_size;

static void Audio_Stop(void)
{
    HAL_TIM_Base_Stop_IT(&TIM17_Handler);
    clip_data = NULL;
    Set_Speaker_Duty(128, 128);
    HAL_TIM_PWM_Stop(&htim14, TIM_CHANNEL_1);
    HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_1);
}

void Audio_StopPlayback(void)
{
    uint32_t primask = __get_PRIMASK();
    __disable_irq();
    Audio_Stop();
    __set_PRIMASK(primask);
}

static void Audio_StartClip(const uint8_t *data, uint16_t size)
{
    uint32_t primask = __get_PRIMASK();
    __disable_irq();

    /* Replace an active clip as a unit before TIM17 can read the new state. */
    if (clip_data != NULL)
        Audio_Stop();

    predictor = 0;
    step_index = 0;
    adpcm_byte_pos = 0;
    use_high_nibble = 0;
    clip_size = size;
    clip_data = data;

    Set_Speaker_Duty(128, 128);
    HAL_TIM_PWM_Start(&htim14, TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
    __HAL_TIM_SET_COUNTER(&TIM17_Handler, 0);
    __HAL_TIM_CLEAR_FLAG(&TIM17_Handler, TIM_FLAG_UPDATE);
    HAL_TIM_Base_Start_IT(&TIM17_Handler);
    __set_PRIMASK(primask);
}

void Audio_Start(void)
{
    Audio_StartClip(audio_adpcm_data, sizeof(audio_adpcm_data));
}

void Audio_PlayPass(void)
{
    Audio_StartClip(pass_adpcm_data, sizeof(pass_adpcm_data));
}

void Audio_PlayResult(void)
{
    Audio_StartClip(result_adpcm_data, sizeof(result_adpcm_data));
}

void Audio_PlayCountdown(void)
{
    Audio_StartClip(countdown_adpcm_data, sizeof(countdown_adpcm_data));
}

void Audio_CancelCountdown(void)
{
    uint32_t primask = __get_PRIMASK();
    __disable_irq();
    if (clip_data == countdown_adpcm_data)
        Audio_Stop();
    __set_PRIMASK(primask);
}

void Audio_PlayTimeout(void)
{
    Audio_StartClip(timeout_adpcm_data, sizeof(timeout_adpcm_data));
}

/* Decode a single IMA-ADPCM sample and clamp before narrowing to int16_t. */
static int16_t ADPCM_Decode(uint8_t nibble)
{
    int16_t step = ima_step_table[step_index];
    int32_t diff = step >> 3;
    int32_t next;

    if (nibble & 1u) diff += step >> 2;
    if (nibble & 2u) diff += step >> 1;
    if (nibble & 4u) diff += step;

    next = predictor + ((nibble & 8u) ? -diff : diff);
    if (next > 32767) next = 32767;
    if (next < -32768) next = -32768;
    predictor = (int16_t)next;

    step_index += ima_index_table[nibble & 0x0Fu];
    if (step_index < 0) step_index = 0;
    if (step_index > 88) step_index = 88;
    return predictor;
}

void Audio_OnTimerTick(void)
{
    const uint8_t *data = clip_data;
    uint8_t byte;
    uint8_t nibble;
    uint8_t pwm;
    int32_t sample;

    if (data == NULL)
        return;
    if (adpcm_byte_pos >= clip_size)
    {
        Audio_Stop();
        return;
    }

    byte = data[adpcm_byte_pos];
    if (use_high_nibble)
    {
        nibble = byte >> 4;
        ++adpcm_byte_pos;
    }
    else
        nibble = byte & 0x0Fu;
    use_high_nibble ^= 1u;

    sample = (int32_t)ADPCM_Decode(nibble) * AUDIO_VOLUME_PERCENT / 100;
    if (sample > 32767) sample = 32767;
    if (sample < -32768) sample = -32768;
    pwm = (uint8_t)((sample + 32768) >> 8);
    Set_Speaker_Duty(pwm, 255u - pwm);
}
