// 单样本解码: 输入4bit nibble, 输出16bit PCM
int16_t ADPCM_Decode(uint8_t nibble)
{
    int16_t step = ima_step_table[step_index];
    int32_t diff = step >> 3;       // step/8
    
    if (nibble & 1) diff += step >> 2;   // +step/4
    if (nibble & 2) diff += step >> 1;   // +step/2
    if (nibble & 4) diff += step;        // +step
    
    if (nibble & 8) diff = -diff;
    
    predictor += diff;
    if (predictor >  32767) predictor =  32767;
    if (predictor < -32768) predictor = -32768;
    
    step_index += ima_index_table[nibble & 0x0F];
    if (step_index < 0)  step_index = 0;
    if (step_index > 88) step_index = 88;
    
    return predictor;
}